"""Generate mbe_tables.py from the mbelib headers in vocoder/ref/mbelib (ISC licence, see fetch_refs.sh).

Only the AMBE 3600x2450 tables and the synthesis window Ws are taken; commented-out alternatives are dropped.
"""

import os
import re

HERE = os.path.dirname(os.path.abspath(__file__))
MBELIB = os.path.join(HERE, "..", "ref", "mbelib")
NAMES = ("AmbeW0table", "AmbeLtable", "AmbeVuv", "AmbeLmprbl", "AmbeDg", "AmbePRBA24", "AmbePRBA58",
         "AmbeHOCb5", "AmbeHOCb6", "AmbeHOCb7", "AmbeHOCb8", "Ws")


def tables(path):
    src = open(path).read()
    src = re.sub(r"/\*.*?\*/", "", src, flags=re.S)
    out = {}
    for m in re.finditer(r"const\s+(float|int)\s+(\w+)((?:\[\d+\])+)\s*=\s*\{(.*?)\};", src, flags=re.S):
        typ, name, dims, body = m.groups()
        if name not in NAMES:
            continue
        dims = [int(d) for d in re.findall(r"\d+", dims)]
        vals = [(float if typ == "float" else int)(v) for v in re.findall(r"-?\d+(?:\.\d*)?(?:[eE]-?\d+)?", body)]
        n = 1
        for d in dims:
            n *= d
        assert len(vals) == n, (name, len(vals), n)
        if len(dims) == 2:
            vals = [tuple(vals[i:i + dims[1]]) for i in range(0, n, dims[1])]
        out[name] = tuple(vals)
    return out


def main():
    t = tables(os.path.join(MBELIB, "ambe3600x2450_const.h"))
    t.update(tables(os.path.join(MBELIB, "mbelib_const.h")))
    assert set(t) == set(NAMES), set(NAMES) - set(t)
    with open(os.path.join(HERE, "mbe_tables.py"), "w") as f:
        f.write('"""AMBE 3600x2450 tables and the synthesis window, generated by gen_tables.py from mbelib.\n\n')
        f.write("Copyright (C) 2010 mbelib Author, ISC licence (vocoder/ref/mbelib/COPYRIGHT).\n\"\"\"\n\n")
        for name in NAMES:
            f.write("%s = %r\n\n" % (name, t[name]))
    print("mbe_tables.py:", ", ".join("%s[%d]" % (n, len(t[n])) for n in NAMES))


if __name__ == "__main__":
    main()

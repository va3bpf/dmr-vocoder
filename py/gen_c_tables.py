"""Write c/ambe/ambe_tables.c from mbe_tables.py (the AMBE 3600x2450 tables and the synthesis window Ws)."""

import math
import os

import numpy as np

import mbe_tables as T

HERE = os.path.dirname(os.path.abspath(__file__))
OUT = os.path.join(HERE, "..", "c", "ambe", "ambe_tables.c")


def fmt(v, typ):
    return repr(float(v)) + "f" if typ == "float" else "%d" % v


# The tables of the hot loops: AMBE_RAM_DATA (ambe_tables.h) puts them into RAM on the radio, next to the vocoder's
# code (from the flash the decoder took twice as long)
IN_RAM = {"AmbeCosQ12", "AmbeWsQ15", "AmbeSqrtWsQ15",  # the decoder's synthesis
          "AmbeWinTQ12", "AmbeCos2048Q15", "AmbeHammingQ15", "AmbeWi2Q15", "AmbeLpfQ15",
          "AmbeLog2Q12", "AmbeExp2Q15", "AmbeLogPQ16", "AmbeW0BinsQ16",  # the encoder's fits, FFT and quantizer
          "AmbePRBA24Q12", "AmbePRBA58Q12", "AmbeHOCb5Q12", "AmbeHOCb6Q12", "AmbeHOCb7Q12", "AmbeHOCb8Q12",
          "AmbeDgQ12", "AmbePmQ14", "AmbeInvDQ12", "AmbePLo", "AmbePHi"}  # the codebooks, E(P) and the tracker


def array(name, typ, vals):
    pre = "AMBE_RAM_DATA " if name in IN_RAM else ""
    if isinstance(vals[0], (tuple, list)):
        rows = ",\n".join("    {" + ", ".join(fmt(v, typ) for v in r) + "}" for r in vals)
        return "%sconst %s %s[%d][%d] = {\n%s\n};\n" % (pre, typ, name, len(vals), len(vals[0]), rows)
    body = ",\n".join("    " + ", ".join(fmt(v, typ) for v in vals[i:i + 8]) for i in range(0, len(vals), 8))
    return "%sconst %s %s[%d] = {\n%s\n};\n" % (pre, typ, name, len(vals), body)


def main():
    types = {"AmbeLtable": "int", "AmbeVuv": "int", "AmbeLmprbl": "int"}
    out = ["/* Generated by py/gen_c_tables.py from py/mbe_tables.py (mbelib's tables, ISC licence). */",
           '#include "ambe_tables.h"', ""]
    for name in ("AmbeW0table", "AmbeLtable", "AmbeVuv", "AmbeLmprbl", "AmbeDg", "AmbePRBA24", "AmbePRBA58",
                 "AmbeHOCb5", "AmbeHOCb6", "AmbeHOCb7", "AmbeHOCb8", "Ws"):
        typ = types.get(name, "float")
        vals = getattr(T, name)
        if typ == "int":
            vals = [tuple(int(v) for v in r) for r in vals] if isinstance(vals[0], (tuple, list)) \
                else [int(v) for v in vals]
        out.append(array(name, "signed char" if name == "AmbeVuv" else typ, vals))
    # fixed-point tables of the embedded vocoder (c/ambe)
    # a quarter of the circle (cos_q12() folds the rest: the rounded values are as symmetric as the cosine)
    out.append(array("AmbeCosQ12", "short", [int(round(4096 * math.cos(2 * math.pi * i / 4096))) for i in range(1025)]))
    out.append(array("AmbeWsQ15", "short", [min(32767, int(round(32768 * w))) for w in T.Ws]))
    out.append(array("AmbeSqrtWsQ15", "short", [min(32767, int(round(32768 * math.sqrt(w)))) for w in T.Ws]))
    disp = np.random.default_rng(12345).uniform(-math.pi, math.pi, 58)  # ambe_decoder.PHASE_DISP
    disp[0] = 0.0
    out.append(array("AmbePhaseDispQ32", "int", [int(round(v / (2 * math.pi) * 2 ** 32)) for v in disp]))
    # the codebooks in Q12 (all within +-8), log2 / exp2 tables for the integer decoder
    q12 = lambda v: int(round(4096 * v))
    out.append(array("AmbeDgQ12", "short", [q12(v) for v in T.AmbeDg]))
    for name in ("AmbePRBA24", "AmbePRBA58", "AmbeHOCb5", "AmbeHOCb6", "AmbeHOCb7", "AmbeHOCb8"):
        out.append(array(name + "Q12", "short", [tuple(q12(v) for v in r) for r in getattr(T, name)]))
    out.append(array("AmbeLog2Q12", "short", [q12(math.log2(1 + i / 256)) for i in range(257)]))
    out.append(array("AmbeExp2Q15", "unsigned short", [min(65535, int(round(32768 * 2 ** (i / 256)))) for i in range(257)]))
    # the integer encoder (ambe_enc.c; the constants of ambe_analysis.py)
    out.append(array("AmbeCos2048Q15", "short", [min(32767, int(round(32768 * math.cos(2 * math.pi * i / 2048))))
                                                for i in range(513)]))  # a quarter, cos2048_q15() folds
    ham = np.hamming(256)
    out.append(array("AmbeHammingQ15", "short", [min(32767, int(round(32768 * v))) for v in ham]))
    wi = np.hamming(301) ** 2
    wi2 = wi / wi.sum()
    out.append(array("AmbeWi2Q15", "short", [min(32767, int(round(32768 * v / wi2.max()))) for v in wi2]))
    t = np.arange(-10, 11)
    lpf = np.sinc(2 * 1000 / 8000 * t) * np.hamming(21)
    lpf /= lpf.sum()
    out.append(array("AmbeLpfQ15", "short", [int(round(32768 * v)) for v in lpf]))
    # the analysis window's transform without its linear phase (real, even), 64 points a bin, / its peak, Q12
    n = np.arange(256) - 127.5
    # 32 points a 1024-point bin (64 gave no better fits, at twice the RAM)
    wa = [np.sum(ham * np.cos(2 * math.pi * i / 32768 * n)) for i in range(32 * 64 + 1)]
    out.append(array("AmbeWinTQ12", "short", [int(round(4096 * v / wa[0])) for v in wa]))
    out.append(array("AmbeW0BinsQ16", "int", [int(round(f * 1024 * 65536)) for f in T.AmbeW0table]))
    # the pitch tracker's grid P = 20 .. 128 in half samples
    P = np.arange(20, 128.25, 0.5)
    sw4 = np.sum(wi2 ** 2)
    out.append(array("AmbeLogPQ16", "int", [int(round(65536 * math.log(p))) for p in P]))
    out.append(array("AmbePmQ14", "short", [int(round(16384 * p * wi2.max())) for p in P]))
    out.append(array("AmbeInvDQ12", "short", [int(round(4096 / (1 - p * sw4))) for p in P]))
    lo = np.searchsorted(P, 0.8 * P - 1e-9)
    hi = np.searchsorted(P, 1.2 * P + 1e-9)
    out.append(array("AmbePLo", "unsigned char", [int(v) for v in lo]))
    out.append(array("AmbePHi", "unsigned char", [int(v) for v in hi]))
    # Golay(23,12): syndrome -> the error pattern of weight <= 3 (the code is perfect)
    from itertools import combinations

    import ambe_frame
    err = [0] * 2048
    for w in range(4):
        for bits in combinations(range(23), w):
            e = sum(1 << i for i in bits)
            err[ambe_frame._syndrome(e)] = e
    out.append(array("AmbeGolayErr", "unsigned int", err))
    open(OUT, "w", newline="\n").write("\n".join(out))


if __name__ == "__main__":
    main()
